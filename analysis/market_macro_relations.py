def build_macro_relations(series, prices, specs, end, relationship):
    """Use fixed windows so every factor remains visible across daily/monthly queries."""
    day = dt.date.fromisoformat(end)
    next_month = (day.replace(day=28) + dt.timedelta(days=4)).replace(day=1)
    monthly_prices = prices if day == next_month - dt.timedelta(days=1) else [
        row for row in prices if row["date"][:7] < end[:7]]
    result = []
    for group in GROUPS:
        for key in GROUP_KEYS[group["key"]]:
            spec = specs.get(key)
            if not spec or key not in RELATIONS:
                continue
            frequency = spec["frequency"]
            if frequency == "quarterly":
                evidence = {"frequency": frequency, "window": None, "lag": 0, "n": 0,
                            "rho": None, "spearman": None, "start": None, "end": None,
                            "status": "季频环境观察，不混入日/月频相关", "x_unit": "百分点", "y_unit": "指数对数收益%",
                            "note": "GDP只展示统计口径与传导机制，未估计季度相关系数。"}
            else:
                window = 60 if frequency == "monthly" else 252
                rows = series.get(key, [])
                raw = relationship(monthly_prices if frequency == "monthly" else prices, rows, spec,
                                   window=window, lag=0, frequency=frequency)
                stats = {name: value for name, value in raw.items() if name not in ("pairs", "stability")}
                note = ("完整统计月份按相邻月变化配对，未还原历史发布版本；不作为实时交易回测。"
                        if frequency == "monthly" else
                        "按指数交易日匹配变化；美国观测严格早于A股日期，重复沿用值不增加样本。")
                if key == "m1":
                    note += "M1仅使用2025年新口径后的相邻月变化。"
                elif key == "spending":
                    note += "剔除跨年累计口径重置的变化。"
                evidence = {**stats, "frequency": frequency, "window": window, "lag": 0,
                            "note": note}
            result.append({"key": key, "name": spec["name"], "group": group["key"], "frequency": frequency,
                           **deepcopy(RELATIONS[key]), "evidence": evidence})
    return {"groups": deepcopy(GROUPS), "rows": result,
            "note": "传导机制是基于指标口径的条件分析，不是固定涨跌规律。历史证据使用当前研究指数，固定日频252个交易日/月频60个完整月份、额外领先期0；不随下方单因子窗口调整。日频至少60、月频至少24个有效配对，缺失不填零。相关不等于因果，也不代表预测能力；行业列表为机制观察方向，不是实测收益排名。"}
